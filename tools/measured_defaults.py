#!/usr/bin/env python3
"""Turn a guided measurement (calibration.json from a .ramesure) into the simulator's built-in envelope, LFO and
envelope-shape tables: Source/sim/RaMeasured.inc. Numbers only: the cymbal recordings of a unit never go in the
code. The LFO below 71 is redrawn from the faster speeds (one octave every 7.6 steps there): the measurement can't
see the slow ones.

    python3 -I tools/measured_defaults.py path/to/calibration.json "where it comes from" > Source/sim/RaMeasured.inc
"""
import json, math, sys

cal = json.load(open(sys.argv[1]))
origin = sys.argv[2] if len(sys.argv) > 2 else 'a unit'

def num(v):
    t = '%.4g' % v
    if '.' not in t and 'e' not in t:
        t += '.0'
    return t + 'f'

def table(name, values):
    out = [f'static const std::array<float, 128> {name} {{']
    for i in range(0, 128, 8):
        out.append('    ' + ', '.join(num(v) for v in values[i:i + 8]) + ',')
    out.append('};')
    return '\n'.join(out)

lfo = list(cal['lfoHz'])
# the speeds that doubled steadily on the unit (71 .. 111): a straight line in octaves, used below 71
pts = [(71, lfo[71]), (111, lfo[111])]
slope = math.log2(pts[1][1] / pts[0][1]) / (pts[1][0] - pts[0][0])
for v in range(0, 71):
    lfo[v] = pts[0][1] * 2 ** ((v - 71) * slope)

print(f'// Generated by tools/measured_defaults.py from the guided measurement of {origin}.')
print('// The envelopes (measured on Envelope 2, the one that shapes the level), the LFO speeds and the shape curves.')
print()
print(table('measuredAttackMs', cal['attackMs']))
print(table('measuredDecayMs', cal['decayMs']))
print(table('measuredReleaseMs', cal['releaseMs']))
print(table('measuredLfoHz', lfo))
curves = cal['fallCurves']
print(f'static const std::array<std::array<float, 64>, {len(curves)}> measuredFallCurves {{ {{')
for c in curves:
    print('    { ' + ', '.join(num(v) for v in c) + ' },')
print('} };')
print(f'static constexpr float measuredCutoffModSemitones = {cal["cutoffModSemitones"]:.2f}f;')
print(f'static constexpr float measuredPitchModSemitones = {cal["pitchModSemitones"]:.2f}f;')
